fn is_light_surface_dock(tb_theme: TaskbarTheme) -> bool {
    crate::dock_themes::dock_palette(tb_theme)
        .map(|pal| {
            let lum = (pal.glass_top.0 as u32 * 299
                + pal.glass_top.1 as u32 * 587
                + pal.glass_top.2 as u32 * 114)
                / 1000;
            lum > 155
        })
        .unwrap_or(false)
}

