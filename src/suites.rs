pub fn suites_in_category(cat: SuiteCategory) -> Vec<(usize, &'static SuitePreset)> {
    SUITES
        .iter()
        .enumerate()
        .filter(|(_, s)| cat == SuiteCategory::All || s.category == cat)
        .collect()
}

pub fn find_suite_by_id(id: &str) -> Option<&'static SuitePreset> {
    let clean = id.trim();
    if clean.is_empty() {
        return None;
    }
    SUITES.iter().find(|s| s.id.eq_ignore_ascii_case(clean))
}

fn suite_theme_dirs() -> Vec<PathBuf> {
    let mut dirs = vec![app_data_dir().join("Themes").join("Suite_Themes")];
    if let Some(exe_dir) = self_exe_path().parent() {
        let p = exe_dir.join("Themes").join("Suite_Themes");
        if !dirs.iter().any(|d| d == &p) {
            dirs.push(p);
        }
    }
    dirs
}

