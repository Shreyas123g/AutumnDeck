    #[test]
    fn verify_zero_overlap_and_screen_bounds_for_all_30_suites() {
        for s in &SUITES {
            let boxes = suite_widget_preview_boxes(s);
            let max_y = if s.tb_theme.uses_virtual_dock() && s.dock_edge == MacDockEdge::Bottom {
                715.0
            } else {
                792.0
            };
            let min_y = if s.tb_theme.uses_virtual_dock() && s.dock_edge == MacDockEdge::Top {
                72.0
            } else {
                12.0
            };
            let min_x = if s.tb_theme.uses_virtual_dock() && s.dock_edge == MacDockEdge::Left {
                82.0
            } else {
                16.0
            };
            let max_x = if s.tb_theme.uses_virtual_dock() && s.dock_edge == MacDockEdge::Right {
                1200.0
            } else {
                1268.0
            };
            for (idx, &(x, y, w, h)) in boxes.iter().enumerate() {
                let fx = x as f32;
                let fy = y as f32;
                assert!(
                    fx >= min_x && fy >= min_y && fx + w <= max_x && fy + h <= max_y,
                    "Suite '{}' box #{} ({},{},{}x{}) out of safe canvas bounds",
                    s.id,
                    idx,
                    x,
                    y,
                    w,
                    h
                );
            }
            for i in 0..boxes.len() {
                for j in (i + 1)..boxes.len() {
                    let (ax, ay, aw, ah) = boxes[i];
                    let (bx, by, bw, bh) = boxes[j];
                    let overlap_x = (ax as f32) < (bx as f32 + bw + 8.0)
                        && (bx as f32) < (ax as f32 + aw + 8.0);
                    let overlap_y = (ay as f32) < (by as f32 + bh + 8.0)
                        && (by as f32) < (ay as f32 + ah + 8.0);
                    assert!(
                        !(overlap_x && overlap_y),
                        "Suite '{}' has overlap between widget #{} ({},{},{}x{}) and #{} ({},{},{}x{})",
                        s.id,
                        i,
                        ax,
                        ay,
                        aw,
                        ah,
                        j,
                        bx,
                        by,
                        bw,
                        bh
                    );
                }
            }
        }
    }

